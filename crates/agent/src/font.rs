/// U+00B0, the degree sign.
const DEGREE: Glyph = [0x1C, 0x36, 0x36, 0x1C, 0x00, 0x00, 0x00, 0x00];

/// `?`, for a character the font hasn't.
const UNKNOWN: Glyph = BASIC[(b'?' - b' ') as usize];

/// The glyph of `c`: ASCII 32 to 126 and `°`, else `?`.
pub fn glyph(c: char) -> &'static Glyph {
    match c {
        ' '..='~' => &BASIC[c as usize - ' ' as usize],
        '°' => &DEGREE,
        _ => &UNKNOWN,
    }
}

/// Whether pixel (`x`, `y`) of `g` is ink, (0, 0) being its top left.
pub fn ink(g: &Glyph, x: u32, y: u32) -> bool {
    x < CELL && y < CELL && g[y as usize] >> x & 1 == 1
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_but_space_has_ink_inside_its_cell() {
        // Bits past the eighth can't exist in a u8, so "inside its cell"
        // is about the rows: eight, the last empty but for descenders.
        for c in (' '..='~').chain(['°']) {
            let g = glyph(c);
            let n: u32 = g.iter().map(|r| r.count_ones()).sum();
            assert_eq!(n == 0, c == ' ', "{c:?} has {n} pixels of ink");
        }
        assert_eq!(glyph('é'), glyph('?'));
        assert_eq!(glyph('\n'), glyph('?'));
    }

    #[test]
    fn the_glyphs_read_as_their_characters() {
        // A few, drawn: bit 0 is the leftmost pixel.
        let art = |c| {
            glyph(c)
                .iter()
                .map(|r| {
                    (0..8)
                        .map(|x| if r >> x & 1 == 1 { '#' } else { '.' })
                        .collect::<String>()
                })
                .collect::<Vec<_>>()
        };
        assert_eq!(
            art('1'),
            [
                "..##....", ".###....", "..##....", "..##....", "..##....", "..##....", "######..",
                "........",
            ]
        );
        assert_eq!(
            art('f'),
            [
                "..###...", ".##.##..", ".##.....", "####....", ".##.....", ".##.....", "####....",
                "........",
            ]
        );
        assert_eq!(
            art('°'),
            [
                "..###...", ".##.##..", ".##.##..", "..###...", "........", "........", "........",
                "........",
            ]
        );
        assert!(ink(glyph('|'), 3, 0) && !ink(glyph('|'), 3, 3) && !ink(glyph('|'), 8, 0));
    }
}
