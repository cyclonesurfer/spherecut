//! The 8×8 font of `look`'s labels (a1-plan section 7.2): the IBM PC
//! BIOS glyphs, ASCII 32 to 126, as Daniel Hepper published them in the
//! public domain (`font8x8_basic.h`, from Marcel Sondaar's and the
//! Linux kernel's tables), plus the degree sign from the same set's
//! `font8x8_ext_latin.h`. The notice: "Public Domain. This file is
//! provided as-is. It comes with no warranty."
//!
//! Each glyph is eight rows, top first; in a row, bit 0 is the leftmost
//! pixel. No font file is read at run time, and no crate is needed.

/// One glyph: eight rows of eight pixels.
pub type Glyph = [u8; 8];

/// The side of a glyph's cell, in pixels at scale 1.
pub const CELL: u32 = 8;

