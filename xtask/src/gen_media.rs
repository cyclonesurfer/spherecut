//! `cargo xtask gen-media`: write the synthetic test-media set.

use std::fmt::Write as _;
use std::path::PathBuf;
use std::time::Instant;

use anyhow::{Context, Result};
use spherecut_synth::media;

use crate::workspace_root;

#[derive(clap::Args)]
pub struct Args {
    /// Output directory (default: test-media/ in the workspace).
    #[arg(long)]
    out: Option<PathBuf>,
    /// Skip the large (4K) file.
    #[arg(long)]
    quick: bool,
}

pub fn run(a: Args) -> Result<()> {
    let dir = a.out.unwrap_or_else(|| workspace_root().join("test-media"));
    std::fs::create_dir_all(&dir).with_context(|| format!("creating {}", dir.display()))?;
    let mut manifest =
        String::from("# Synthetic test media\n\nGenerated by `cargo xtask gen-media`.\n\n");
    let mut first = None;
    for spec in media::standard_set() {
        if a.quick && spec.width > 2048 {
            continue;
        }
        let t = Instant::now();
        let path = media::write(&spec, &dir).with_context(|| format!("writing {}", spec.name))?;
        eprintln!("  {} ({:.1} s)", path.display(), t.elapsed().as_secs_f64());
        let _ = writeln!(
            manifest,
            "- `{}`: {:?} {}x{} @ {} fps, {} frames, {:?} {}-bit, audio {:?}, spherical metadata {}",
            spec.file_name(),
            spec.pattern,
            spec.width,
            spec.height,
            spec.rate,
            spec.frames,
            spec.codec,
            spec.bits,
            spec.audio,
            if spec.spherical { "yes" } else { "no" }
        );
        first.get_or_insert(path);
    }
    if let Some(good) = first {
        for p in media::write_bad_files(&good, &dir)? {
            eprintln!("  {}", p.display());
            let _ = writeln!(
                manifest,
                "- `{}`: deliberately broken",
                p.file_name()
                    .map(|n| n.to_string_lossy())
                    .unwrap_or_default()
            );
        }
    }
    std::fs::write(dir.join("MANIFEST.md"), manifest)?;
    eprintln!("==> test media in {}", dir.display());
    Ok(())
}
